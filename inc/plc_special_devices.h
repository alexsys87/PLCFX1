/**
 * @file plc_special_devices.h
 * @brief Names of the FX special data registers (D8000..D8255) and special relays (M8000..M8255).
 *
 * Both areas live in the PLC image (see plc_memory_map.h). A D8xxx name expands to an lvalue
 * for the 16-bit register; an M8xxx name expands to the *linear bit address* of the relay, to be
 * used with PLC_BIT_TEST()/PLC_BIT_ON()/PLC_BIT_OFF().
 *
 * Special devices that this firmware gives a meaning (all others are plain storage):
 *
 *   Relay   Meaning
 *   M8000   RUN monitor: ON while the PLC runs
 *   M8001   STOP monitor: ON while the PLC is stopped
 *   M8002   initial pulse: ON during the first scan after RUN (M8003 is its inverse)
 *   M8011..M8014  clocks: 10 ms, 100 ms, 1 s and 1 min square waves (50 % duty)
 *   M8020..M8022  zero, borrow and carry flags of arithmetic/rotate/shift instructions
 *   M8029   instruction execution complete (SORT/SORT2)
 *   M8048   annunciator flag, enabled by M8049 (ANS/ANR)
 *   M8063   retained-data/flash error, M8065 program error (the fault code is in D8067)
 *   M8161, M8165, M8168  instruction modes: 8-bit mode (CCD), descending sort (SORT2),
 *           BCD data in SMOV; driven by the user program
 *   M8200+n direction of the 32-bit counter C(200+n): ON counts down
 *
 *   Register  Meaning
 *   D8013..D8019  real-time clock: second, minute, hour, day, month, year, weekday
 *   D8028/D8029   index registers Z0 and V0 (Z1..Z7 / V1..V7 are D8182..D8195)
 *   D8049   number of the lowest active annunciator (S900..S999)
 *   D8067   last runtime fault code, D8068/D8069 program step of the fault
 *   D8120   communication format of the FX protocol: not interpreted, the programming
 *           port is fixed at 19200 baud 8N1 (see plc_serial_protocol.c)
 *
 * Programs may drive only the mode/user relays M8030..M8059 and M8100..M8255; the experimental
 * interpreter rejects writes to the status, clock, flag and error relays (see plc_exp_operands.c).
 */
